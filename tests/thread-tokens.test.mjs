import { test } from "node:test";
import assert from "node:assert/strict";
import { mkdtempSync, readFileSync, writeFileSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { spawnSync } from "node:child_process";

test("token CLI checks run-window phases, repository isolation and unassigned overhead read-only", () => {
  const directory = mkdtempSync(join(tmpdir(), "pstack-usage-"));
  const database = join(directory, "state.sqlite");
  try {
    const setup = spawnSync("python3", ["-c", "import sqlite3,sys; c=sqlite3.connect(sys.argv[1]); c.executescript(open(sys.argv[2]).read()); c.close()", database, resolve("tests/fixtures/thread-tokens.sql")], { encoding: "utf8" });
    assert.equal(setup.status, 0, setup.stderr);
    const token = (ms, input, cached, output) => ({ timestamp: new Date(ms).toISOString(), type: "event_msg", payload: { type: "token_count", info: { total_token_usage: { input_tokens: input, cached_input_tokens: cached, output_tokens: output } } } });
    const events = [token(900, 100, 80, 10), token(1000, 1000, 800, 110), token(1001, 1000, 800, 110),
      { timestamp: new Date(1050).toISOString(), type: "event_msg", payload: { type: "user_message", message: '{"state":"code-ready"}' } },
      { timestamp: new Date(1100).toISOString(), type: "event_msg", payload: { type: "agent_message", message: '{"state": "code-ready"}' } },
      token(1200, 1400, 1100, 160), token(2000, 9999, 5000, 999)];
    writeFileSync(join(directory, "owner.jsonl"), events.map(e => JSON.stringify(e)).join("\n"));
    const before = readFileSync(database);
    const run = (...options) => spawnSync("python3", [resolve("scripts/thread-tokens.py"), database, "--since", "1000", "--until", "2000", ...options], { encoding: "utf8" });
    const result = run("--check");
    assert.equal(result.status, 1, result.stderr);
    const report = JSON.parse(result.stdout);
    const group = report.groups[JSON.stringify(["repo-a", "PR #12"])];
    assert.deepEqual(group.O, { uncached_input: 180, cached_input: 720, output: 100, model_turns: 1, unknown_tokens: 0 });
    assert.deepEqual(group.H, { uncached_input: 100, cached_input: 300, output: 50, model_turns: 1, unknown_tokens: 35 });
    assert.equal(group.overhead_to_owner, 0.485);
    assert.equal(group.verifier_threads, 3);
    assert.equal(report.violations.length, 3);
    assert.equal(report.violations.filter(v => v.startsWith("unnamed child:")).length, 0);
    assert.equal(report.excluded_foreign_threads, 2);
    assert.deepEqual(report.unassigned, { threads: 2, uncached_input: 0, cached_input: 0, output: 0, model_turns: 0, unknown_tokens: 50 });
    assert.equal(Object.keys(report.groups).length, 4);
    const cloudReceipt = JSON.stringify(["repo-a", "PR #13", "cloud-task-13"]);
    const cloud = run("--cloud-owner", cloudReceipt, "--check");
    const cloudReport = JSON.parse(cloud.stdout);
    const cloudGroup = cloudReport.groups[JSON.stringify(["repo-a", "PR #13"])];
    assert.equal(cloudGroup.O, null);
    assert.equal(cloudGroup.owner_status, "unbekannt (Cloud)");
    assert.equal(cloudGroup.overhead_to_owner, null);
    assert.deepEqual(cloudGroup.cloud_owner_tasks, ["cloud-task-13"]);
    assert.equal(cloudReport.hints.length, 1);
    assert.equal(cloudReport.violations.length, 2);
    assert.equal(cloud.status, 1, "local violations must remain red");
    assert.ok(cloudReport.violations.some(v => v.includes("H/O > 1/3") && v.includes("PR #12")));
    const cloudOnly = run("--since", "1450", "--until", "1451", "--cloud-owner", cloudReceipt, "--check");
    assert.equal(cloudOnly.status, 0, cloudOnly.stderr);
    assert.equal(JSON.parse(cloudOnly.stdout).violations.length, 0);
    const wrongRepo = run("--cloud-owner", JSON.stringify(["repo-b", "PR #13", "cloud-task-13"]), "--check");
    assert.equal(JSON.parse(wrongRepo.stdout).violations.length, 3);
    const cloudLocal = run("--cloud-owner", JSON.stringify(["repo-a", "PR #12", "cloud-task-12"]), "--check");
    const localGroup = JSON.parse(cloudLocal.stdout).groups[JSON.stringify(["repo-a", "PR #12"])];
    assert.deepEqual(localGroup.O_local, group.O);
    assert.ok(JSON.parse(cloudLocal.stdout).violations.some(v => v.includes("verifier threads > 2")));
    assert.equal(run("--cloud-owner", '["repo-a"]').status, 2);
    const isolated = run("--repo", "repo-b", "--check");
    assert.equal(isolated.status, 0, isolated.stderr);
    assert.equal(Object.keys(JSON.parse(isolated.stdout).groups).length, 1);
    const cwd = run("--repo", "/sample/a");
    assert.equal(cwd.status, 0, cwd.stderr);
    assert.equal(Object.keys(JSON.parse(cwd.stdout).groups).length, 3);
    const explicit = run("--root-thread", "9", "--check");
    assert.equal(JSON.parse(explicit.stdout).unassigned.threads, 1);
    const native = run("--since", "3000", "--until", "3001", "--root-thread", "native-root", "--check");
    const nativeReport = JSON.parse(native.stdout);
    assert.deepEqual(nativeReport.root_threads, ["native-root"]);
    assert.deepEqual(Object.keys(nativeReport.groups), [JSON.stringify(["repo-native", "PR #218"])]);
    const nativeGroup = Object.values(nativeReport.groups)[0];
    assert.equal(nativeGroup.O.unknown_tokens, 600);
    assert.equal(nativeGroup.H.unknown_tokens, 15);
    assert.equal(nativeGroup.verifier_threads, 1);
    assert.deepEqual(nativeReport.violations, ["unnamed child: native-unnamed (parent native-root)"]);
    assert.equal(native.status, 1, "truly unnamed children still fail");
    assert.equal(nativeReport.unassigned.threads, 3);
    const subtree = run("--since", "3000", "--until", "3001", "--root-thread", "native-owner", "--check");
    assert.equal(subtree.status, 0, subtree.stderr);
    const subtreeReport = JSON.parse(subtree.stdout);
    assert.deepEqual(subtreeReport.root_threads, ["native-owner"]);
    assert.equal(Object.values(subtreeReport.groups)[0].threads, 2);
    assert.equal(subtreeReport.unassigned.threads, 0);
    const foreign = run("--since", "3000", "--until", "3001", "--root-thread", "foreign-root", "--check");
    const foreignReport = JSON.parse(foreign.stdout);
    assert.equal(foreign.status, 1);
    assert.ok(foreignReport.violations.some(v => v.includes("3 verifier threads > 2")));
    assert.ok(foreignReport.violations.some(v => v.includes("H/O > 1/3")));
    const both = run("--since", "3000", "--until", "3001", "--root-thread", "native-root", "--root-thread", "foreign-root");
    assert.equal(Object.keys(JSON.parse(both.stdout).groups).length, 2);
    assert.equal(run("--root-thread", "missing").status, 2);
    const unbound = run("--since", "4000", "--until", "4001", "--root-thread", "native-root", "--check");
    assert.equal(unbound.status, 1);
    assert.equal(Object.values(JSON.parse(unbound.stdout).groups)[0].O.unknown_tokens, 0);
    const children = join(directory, "children.tsv");
    writeFileSync(children, "handle\trole\tstate\tscope\n"
      + "/root/b2u_owner\tslice:B2u owner\trunning\tbefore PR\n"
      + "/root/b2u_owner\tPR #226 owner Personenfilter\tHOLD\tafter PR\n");
    const bound = run("--since", "4000", "--until", "4001", "--root-thread", "native-root", "--children-tsv", children, "--check");
    assert.equal(bound.status, 0, bound.stderr);
    const boundReport = JSON.parse(bound.stdout);
    assert.deepEqual(Object.keys(boundReport.groups), [JSON.stringify(["repo-native", "PR #226"])]);
    const boundGroup = Object.values(boundReport.groups)[0];
    assert.equal(boundGroup.O.unknown_tokens, 300, "foreign owner with the same path stays excluded");
    assert.equal(boundGroup.H.unknown_tokens, 10);
    assert.equal(boundGroup.verifier_threads, 1);
    assert.equal(boundReport.unassigned.threads, 0);
    const ambiguous = run("--since", "4000", "--until", "4001", "--root-thread", "native-root", "--root-thread", "foreign-root", "--children-tsv", children);
    assert.equal(ambiguous.status, 1);
    assert.match(ambiguous.stderr, /Ambiguous children handle/);
    writeFileSync(children, "handle\trole\nprepr-owner\tPR #226 owner\n");
    const byId = run("--since", "4000", "--until", "4001", "--root-thread", "native-root", "--children-tsv", children, "--check");
    assert.equal(byId.status, 0, byId.stderr);
    writeFileSync(children, "wrong\theader\n");
    const malformed = run("--root-thread", "native-root", "--children-tsv", children);
    assert.equal(malformed.status, 1);
    assert.match(malformed.stderr, /requires handle and role columns/);
    const defaultState = join(directory, "state_5.sqlite");
    writeFileSync(defaultState, before);
    const implicitDatabase = spawnSync("python3", [resolve("scripts/thread-tokens.py"), "--root-thread", "foreign-root", "--check"],
      { encoding: "utf8", env: { ...process.env, CODEX_HOME: directory } });
    assert.equal(implicitDatabase.status, 1);
    assert.deepEqual(JSON.parse(implicitDatabase.stdout).root_threads, ["foreign-root"]);
    assert.deepEqual(readFileSync(database), before);
    assert.equal(spawnSync("python3", [resolve("scripts/thread-tokens.py"), join(directory, "missing.sqlite")]).status, 1);
  } finally {
    rmSync(directory, { recursive: true, force: true });
  }
});
